"""Tables, as SQLAlchemy models.

Every table of user data inherits :class:`Owned`; the few that do not are listed in
:data:`GLOBAL_TABLES`, and a test fails when a table is in neither group.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any, Final
from uuid import UUID

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Double,
    Index,
    Integer,
    MetaData,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import JSONB, TIMESTAMP
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

__all__ = [
    "GLOBAL_TABLES",
    "QUEUE_PREFIX",
    "AuditRow",
    "Base",
    "JobRow",
    "Owned",
    "PortfolioRow",
    "is_queue_object",
]

GLOBAL_TABLES: Final = frozenset({"audit_log"})
"""Tables without an owner column: they hold no data a user edits."""

QUEUE_PREFIX: Final = "procrastinate_"
"""Prefix of the tables, types and functions of the job queue (ADR-0046).

Procrastinate creates and migrates them (through our migrations, from its own SQL); they are
not models here, so schema comparisons and autogenerated migrations leave them alone.
"""

FINISHED: Final = "('succeeded', 'failed', 'cancelled')"


def is_queue_object(name: str | None) -> bool:
    """Whether a table, index or type belongs to the queue rather than to these models."""
    return name is not None and name.startswith(QUEUE_PREFIX)


TIMESTAMPTZ: Final = TIMESTAMP(timezone=True)


class Base(DeclarativeBase):
    """Base of every model, with stable names for constraints and indexes."""

    metadata = MetaData(
        naming_convention={
            "ix": "ix_%(table_name)s_%(column_0_N_name)s",
            "uq": "uq_%(table_name)s_%(column_0_N_name)s",
            "ck": "ck_%(table_name)s_%(constraint_name)s",
            "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
            "pk": "pk_%(table_name)s",
        }
    )


class Owned:
    """Mixin of every table of user data: each row belongs to one owner."""

    owner_id: Mapped[str] = mapped_column(Text, nullable=False)


class PortfolioRow(Owned, Base):
    """A saved portfolio (see :class:`investinglab.ports.PortfolioSpec`)."""

    __tablename__ = "portfolios"
    __table_args__ = (
        UniqueConstraint("owner_id", "name"),
        CheckConstraint("owner_id <> ''", name="owner_not_empty"),
        CheckConstraint("name <> ''", name="name_not_empty"),
        CheckConstraint("version >= 1", name="version_positive"),
        Index("ix_portfolios_owner_updated", "owner_id", "updated_at", "id"),
    )

    id: Mapped[UUID] = mapped_column(PG_UUID(as_uuid=True), primary_key=True)
    name: Mapped[str] = mapped_column(Text, nullable=False)
    definition: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    version: Mapped[int] = mapped_column(nullable=False)
    created_at: Mapped[datetime] = mapped_column(TIMESTAMPTZ, nullable=False)
    updated_at: Mapped[datetime] = mapped_column(TIMESTAMPTZ, nullable=False)


class AuditRow(Base):
    """An entry of the append-only audit log (see :class:`investinglab.ports.LogEntry`)."""

    __tablename__ = "audit_log"
    __table_args__ = (CheckConstraint("sequence >= 1", name="sequence_positive"),)

    stream: Mapped[str] = mapped_column(Text, primary_key=True)
    sequence: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=False)
    recorded_at: Mapped[datetime] = mapped_column(TIMESTAMPTZ, nullable=False)
    owner_id: Mapped[str | None] = mapped_column(Text)
    kind: Mapped[str] = mapped_column(Text, nullable=False)
    payload: Mapped[str] = mapped_column(Text, nullable=False)
    previous_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    hash: Mapped[str] = mapped_column(String(64), nullable=False)


class JobRow(Owned, Base):
    """A background job (see :class:`investinglab.ports.Job`).

    The rules of its life are constraints, so no code path can store a job that breaks
    them: a result only when it succeeded, an error only when it failed, a finishing instant
    only when it finished.
    """

    __tablename__ = "jobs"
    __table_args__ = (
        CheckConstraint("owner_id <> ''", name="owner_not_empty"),
        CheckConstraint("kind <> ''", name="kind_not_empty"),
        CheckConstraint(
            "status IN ('queued', 'running', 'succeeded', 'failed', 'cancelled')",
            name="status_known",
        ),
        CheckConstraint(
            "progress IS NULL OR (progress >= 0 AND progress <= 1)", name="progress_fraction"
        ),
        CheckConstraint(
            "(status = 'succeeded') = (result IS NOT NULL)", name="result_when_succeeded"
        ),
        CheckConstraint("(status = 'failed') = (error IS NOT NULL)", name="error_when_failed"),
        CheckConstraint(
            f"(status IN {FINISHED}) = (finished_at IS NOT NULL)", name="finished_when_final"
        ),
        CheckConstraint("attempts >= 0", name="attempts_not_negative"),
        Index("ix_jobs_owner_created", "owner_id", "created_at", "id"),
    )

    id: Mapped[UUID] = mapped_column(PG_UUID(as_uuid=True), primary_key=True)
    kind: Mapped[str] = mapped_column(Text, nullable=False)
    status: Mapped[str] = mapped_column(Text, nullable=False)
    parameters: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    result: Mapped[Any] = mapped_column(JSONB(none_as_null=True), nullable=True)
    error: Mapped[dict[str, Any] | None] = mapped_column(JSONB(none_as_null=True))
    progress: Mapped[float | None] = mapped_column(Double)
    stage: Mapped[str | None] = mapped_column(Text)
    cancel_requested: Mapped[bool] = mapped_column(Boolean, nullable=False)
    attempts: Mapped[int] = mapped_column(Integer, nullable=False)
    queue_job_id: Mapped[int | None] = mapped_column(BigInteger)
    created_at: Mapped[datetime] = mapped_column(TIMESTAMPTZ, nullable=False)
    started_at: Mapped[datetime | None] = mapped_column(TIMESTAMPTZ)
    finished_at: Mapped[datetime | None] = mapped_column(TIMESTAMPTZ)
    updated_at: Mapped[datetime] = mapped_column(TIMESTAMPTZ, nullable=False)
